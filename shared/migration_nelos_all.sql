CREATE TABLE IF NOT EXISTS nelos_module_members (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  module_key  TEXT NOT NULL REFERENCES nelos_modules(key) ON DELETE CASCADE,

  -- Email is the handle, because that is what an admin types and because a
  -- person can be added before they have ever signed in. user_id is filled
  -- in when the email matches a shared_profiles row, and is what the app
  -- actually matches on once it is known.
  email       TEXT NOT NULL,
  user_id     UUID REFERENCES shared_profiles(id) ON DELETE CASCADE,
  full_name   TEXT,

  -- Which case categories this person may see in this module.
  -- NULL or empty = every category. Values are nelos_categories.name.
  categories  TEXT[],

  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  created_by  TEXT
);

-- One row per person per module. Case-insensitive, so adding
-- "Ali@mjm.com" twice in different case cannot make two rows.
CREATE UNIQUE INDEX IF NOT EXISTS nelos_module_members_uniq
  ON nelos_module_members (module_key, lower(email));
CREATE INDEX IF NOT EXISTS nelos_module_members_user_idx
  ON nelos_module_members (user_id);
CREATE INDEX IF NOT EXISTS nelos_module_members_email_idx
  ON nelos_module_members (lower(email));

-- Let a key rename carry its member rows with it, instead of failing on the
-- foreign key. The table above may have been created by an earlier run of
-- this file, when the constraint was still ON DELETE only, so this upgrades
-- it in place. Guarded on confupdtype so re-running does not churn it.
DO $$
DECLARE c TEXT;
BEGIN
  SELECT conname INTO c
    FROM pg_constraint
   WHERE conrelid  = 'public.nelos_module_members'::regclass
     AND contype   = 'f'
     AND confrelid = 'public.nelos_modules'::regclass
     AND confupdtype <> 'c';          -- 'c' = already ON UPDATE CASCADE
  IF c IS NOT NULL THEN
    EXECUTE format('ALTER TABLE nelos_module_members DROP CONSTRAINT %I', c);
    ALTER TABLE nelos_module_members
      ADD CONSTRAINT nelos_module_members_module_key_fkey
      FOREIGN KEY (module_key) REFERENCES nelos_modules(key)
      ON UPDATE CASCADE ON DELETE CASCADE;
    RAISE NOTICE 'nelos_module_members.module_key now cascades on rename.';
  END IF;
END $$;

