-- MJM AI POWERED SYSTEM — migration_nelos.sql
--
-- New module: NELOS — Nursery Carlos (nelos_*)
--
-- Nelos is the one place a case lives. Any module can raise a case; every
-- module shows the ones still pending; the case itself is only ever worked
-- on here. Before Nelos, `operation_follow_up_cases` was the only case-like
-- table and only Batch Detail ever wrote to it — nobody had a list of what
-- was outstanding, so cases were raised and then lost.
--
--   1. nelos_categories     — the kinds of case there are (Planting
--                             Discrepancy, Height Shortfall, Pest, …).
--                             Editable from the module's Settings; nothing
--                             is hard-coded, the same way nops_work_types
--                             works for Nursery Operation.
--   2. nelos_cases          — one row per case. Carries WHERE it came from
--                             (source_module + source_ref, so a case can
--                             link back to the exact page that raised it)
--                             and WHAT it is about (nursery / plot / batch,
--                             all optional — a case need not be about any
--                             of them).
--   3. nelos_case_comments  — the thread on a case. Status changes are
--                             written here too, so the history reads as one
--                             list rather than being split across tables.
--
-- Module access: permissions.modules.nelos = 'admin'|'normal'|'none',
-- granted on the main portal's User Access (JSONB — no DDL needed).
-- What somebody sees once inside is decided by which linked modules and
-- categories they are set up for — see migration_nelos_modules.sql and
-- nelos/nelos_user_setting.html.
