-- ────────────────────────────────────────────────────────────────
-- PART 2: Who handles each module's cases
-- ────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS nelos_module_members (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  module_key  TEXT NOT NULL REFERENCES nelos_modules(key) ON DELETE CASCADE,

  -- Email is the handle, because that is what an admin types and because a
  -- person can be added before they have ever signed in. user_id is filled
  -- in when the email matches a shared_profiles row, and is what the app
  -- actually matches on once it is known.
  email       TEXT NOT NULL,
  user_id     UUID REFERENCES shared_profiles(id) ON DELETE CASCADE,
  full_name   TEXT,

  -- Which case categories this person may see in this module.
  -- NULL or empty = every category. Values are nelos_categories.name.
  categories  TEXT[],

  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  created_by  TEXT
);

-- One row per person per module. Case-insensitive, so adding
-- "Ali@mjm.com" twice in different case cannot make two rows.
CREATE UNIQUE INDEX IF NOT EXISTS nelos_module_members_uniq
  ON nelos_module_members (module_key, lower(email));
CREATE INDEX IF NOT EXISTS nelos_module_members_user_idx
  ON nelos_module_members (user_id);
CREATE INDEX IF NOT EXISTS nelos_module_members_email_idx
  ON nelos_module_members (lower(email));

ALTER TABLE nelos_module_members ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
     WHERE schemaname='public' AND tablename='nelos_module_members'
       AND policyname='Authenticated read nelos members'
  ) THEN
    CREATE POLICY "Authenticated read nelos members" ON nelos_module_members
      FOR SELECT TO authenticated USING (true);
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
     WHERE schemaname='public' AND tablename='nelos_module_members'
       AND policyname='Authenticated write nelos members'
  ) THEN
    CREATE POLICY "Authenticated write nelos members" ON nelos_module_members
      FOR ALL TO authenticated USING (true) WITH CHECK (true);
  END IF;
END $$;

-- ────────────────────────────────────────────────────────────────
-- PART 3: Looking somebody up by email
--
-- The User Setting page takes a typed email and needs the matching profile
-- so the member row can carry a user_id and a real name. shared_profiles
-- is readable only for your own row unless you hold manage_users, so this
-- goes through a SECURITY DEFINER function that returns three columns and
-- nothing else — the permissions blob stays unreadable.
-- ────────────────────────────────────────────────────────────────
CREATE OR REPLACE FUNCTION public.nelos_lookup_user(p_email TEXT)
RETURNS TABLE (id UUID, full_name TEXT, email TEXT)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT p.id, p.full_name, p.email
    FROM public.shared_profiles p
   WHERE lower(p.email) = lower(trim(p_email))
   LIMIT 1
$$;

GRANT EXECUTE ON FUNCTION public.nelos_lookup_user(TEXT) TO authenticated;

-- Back-fill user_id on any member row added before that person signed up.
-- Cheap, and it means an admin never has to re-add somebody.
UPDATE nelos_module_members m
   SET user_id   = p.id,
       full_name = COALESCE(m.full_name, p.full_name)
  FROM public.shared_profiles p
 WHERE m.user_id IS NULL
   AND lower(p.email) = lower(m.email);

-- ────────────────────────────────────────────────────────────────
-- PART 4: Check it landed
-- ────────────────────────────────────────────────────────────────
SELECT m.key, m.label, count(mm.id) AS members
  FROM nelos_modules m
  LEFT JOIN nelos_module_members mm ON mm.module_key = m.key
 GROUP BY m.key, m.label, m.sort_order
 ORDER BY m.sort_order;

