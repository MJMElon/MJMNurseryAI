-- MJM AI POWERED SYSTEM — migration_nelos_modules.sql
--
-- NELOS — User Setting: who handles which module's cases.
--
-- Nursery Case Log is linked to several modules. A case raised anywhere
-- lands in that module's block. This migration adds the two tables the
-- User Setting page is built on:
--
--   1. nelos_modules         — the linked modules themselves. A row per
--                              block on the User Setting page. Editable,
--                              so a sixth module is a row rather than a
--                              deploy.
--   2. nelos_module_members  — who handles each module's cases, by email,
--                              and (optionally) which categories they may
--                              see.
--
-- HOW VISIBILITY WORKS — the rule matters, so it is written down once here
-- and implemented once in shared/shared_nelos.js:
--
--   • Nobody has a membership row yet  → they see every case.
--     This is deliberate. Turning the feature on must not blank out the
--     case list for the whole company on day one, and it matches how
--     shared_access.js already treats an unset permission ("a missing key
--     means allowed").
--   • They have at least one membership row → they see cases from those
--     modules only, and within each module only the categories that row
--     allows (an empty/NULL categories array means "all categories in
--     this module").
--   • Nelos admins (permissions.modules.nelos = 'admin') always see
--     everything, whatever their rows say. Without this an admin could
--     lock themselves out of their own case log.
--
-- Requires migration_nelos.sql to have been run first.
-- Run in Supabase SQL Editor (main project: kibqjztozokohqmhqqqf).
-- Safe to re-run: every statement is guarded.
-- ============================================================================

-- ────────────────────────────────────────────────────────────────
-- PART 1: The linked modules
-- ────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS nelos_modules (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  key         TEXT NOT NULL UNIQUE,   -- matches nelos_cases.source_module
  label       TEXT NOT NULL,          -- what the block is called on screen
  icon        TEXT,
  href        TEXT,                   -- where the module lives, from /nelos/
  sort_order  INT  NOT NULL DEFAULT 0,
  active      BOOLEAN NOT NULL DEFAULT true,
  created_at  TIMESTAMPTZ DEFAULT now()
);

ALTER TABLE nelos_modules ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
     WHERE schemaname='public' AND tablename='nelos_modules'
       AND policyname='Authenticated read nelos modules'
  ) THEN
    CREATE POLICY "Authenticated read nelos modules" ON nelos_modules
      FOR SELECT TO authenticated USING (true);
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
     WHERE schemaname='public' AND tablename='nelos_modules'
       AND policyname='Authenticated write nelos modules'
  ) THEN
    CREATE POLICY "Authenticated write nelos modules" ON nelos_modules
      FOR ALL TO authenticated USING (true) WITH CHECK (true);
  END IF;
END $$;

