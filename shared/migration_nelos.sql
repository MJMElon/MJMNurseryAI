-- ────────────────────────────────────────────────────────────────
-- PART 2: Cases
-- ────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS nelos_cases (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  case_no        TEXT UNIQUE,        -- NLS-0001, assigned by trigger below
  title          TEXT NOT NULL,
  description    TEXT,
  category       TEXT,               -- nelos_categories.name, by value not FK
                                     -- so renaming a category never orphans
                                     -- a closed case's history
  priority       TEXT NOT NULL DEFAULT 'normal',  -- low | normal | high | urgent
  status         TEXT NOT NULL DEFAULT 'open',    -- open | in_progress | resolved | closed

  -- Where it came from. source_module is what the To-Do widgets filter on;
  -- source_ref is a link back to the exact page that raised it, written as
  -- seen from a module folder — i.e. starting '../', because the only page
  -- that follows it is nelos/nelos_case.html
  -- (e.g. '../operation/operation_batch_detail.html?batch=264').
  source_module  TEXT NOT NULL DEFAULT 'nelos',   -- operation | audit | scan | nursery_ops | nelos
  source_ref     TEXT,

  -- What it is about. All optional — a case can be about the whole nursery,
  -- one plot, one batch, or nothing physical at all.
  nursery_name   TEXT,
  plot_name      TEXT,
  batch_name     TEXT,

  -- Who owns it. A case is assigned to a person, and that person (or a Nelos
  -- admin) closes it.
  assignee_id    UUID REFERENCES shared_profiles(id) ON DELETE SET NULL,
  assignee_name  TEXT,               -- denormalised so the list renders without
                                     -- reading shared_profiles, which normal
                                     -- users may not select from
  due_date       DATE,

  raised_by      TEXT,
  raised_by_id   UUID REFERENCES shared_profiles(id) ON DELETE SET NULL,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_by     TEXT,
  updated_at     TIMESTAMPTZ,

  resolution     TEXT,               -- what was actually done
  resolved_by    TEXT,
  resolved_at    TIMESTAMPTZ,
  closed_by      TEXT,
  closed_at      TIMESTAMPTZ,

  CONSTRAINT nelos_cases_status_chk
    CHECK (status IN ('open','in_progress','resolved','closed')),
  CONSTRAINT nelos_cases_priority_chk
    CHECK (priority IN ('low','normal','high','urgent'))
);

-- The To-Do list is "pending cases, worst first" — this partial index is the
-- one every dashboard widget hits.
CREATE INDEX IF NOT EXISTS nelos_cases_pending_idx
  ON nelos_cases (priority, due_date NULLS LAST, created_at)
  WHERE status IN ('open','in_progress');
CREATE INDEX IF NOT EXISTS nelos_cases_assignee_idx ON nelos_cases (assignee_id, status);
CREATE INDEX IF NOT EXISTS nelos_cases_source_idx   ON nelos_cases (source_module, status);
CREATE INDEX IF NOT EXISTS nelos_cases_plot_idx     ON nelos_cases (plot_name);
CREATE INDEX IF NOT EXISTS nelos_cases_batch_idx    ON nelos_cases (batch_name);

-- Human case number. A sequence rather than count(*)+1 so two people raising
-- a case in the same second cannot land on the same number.
CREATE SEQUENCE IF NOT EXISTS nelos_case_no_seq START 1;

CREATE OR REPLACE FUNCTION public.nelos_assign_case_no()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF NEW.case_no IS NULL OR NEW.case_no = '' THEN
    NEW.case_no := 'NLS-' || LPAD(nextval('nelos_case_no_seq')::text, 4, '0');
  END IF;
  RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS nelos_cases_case_no ON nelos_cases;
CREATE TRIGGER nelos_cases_case_no
  BEFORE INSERT ON nelos_cases
  FOR EACH ROW EXECUTE FUNCTION public.nelos_assign_case_no();

