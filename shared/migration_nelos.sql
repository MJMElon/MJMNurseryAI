-- ────────────────────────────────────────────────────────────────
-- PART 4: Who a case may be assigned to
--
-- shared_profiles is readable only for your OWN row unless you hold
-- manage_users (see migration_access_and_reviews.sql), so the assignee
-- picker cannot simply select from it. This SECURITY DEFINER function
-- returns the three columns the picker needs and nothing else — the
-- permissions blob stays unreadable. Only people who actually hold Nelos
-- are listed, so a case cannot be assigned to somebody who could never
-- open it.
-- ────────────────────────────────────────────────────────────────
CREATE OR REPLACE FUNCTION public.nelos_assignable_users()
RETURNS TABLE (id UUID, full_name TEXT, email TEXT)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT p.id, p.full_name, p.email
    FROM public.shared_profiles p
   WHERE COALESCE(p.permissions->'modules'->>'nelos', 'none') <> 'none'
   ORDER BY COALESCE(NULLIF(p.full_name, ''), p.email)
$$;

GRANT EXECUTE ON FUNCTION public.nelos_assignable_users() TO authenticated;

-- ────────────────────────────────────────────────────────────────
-- PART 5: Absorb the old operation_follow_up_cases
--
-- Batch Detail used to insert { batch_name, issue_type, status } and
-- nothing else — there was no UI to read them back. Those rows become
-- Nelos cases so the backlog is visible on day one. The old table is
-- LEFT IN PLACE (not dropped) so this migration stays reversible; nothing
-- writes to it any more once operation_batch_detail.html is deployed.
--
-- Guarded by to_regclass: on a database where the table was never created
-- this whole block is skipped rather than erroring.
-- ────────────────────────────────────────────────────────────────
DO $$
DECLARE
  moved INT := 0;
BEGIN
  IF to_regclass('public.operation_follow_up_cases') IS NULL THEN
    RAISE NOTICE 'operation_follow_up_cases does not exist — nothing to absorb.';
    RETURN;
  END IF;

  INSERT INTO nelos_cases (
    title, description, category, priority, status,
    source_module, source_ref, batch_name, raised_by, created_at
  )
  SELECT
    COALESCE(f.issue_type, 'Follow-up') || ' — batch ' || COALESCE(f.batch_name, '?'),
    'Migrated from operation_follow_up_cases (raised by Batch Detail before Nelos existed).',
    COALESCE(f.issue_type, 'Other'),
    'high',
    -- "Pending Investigation" was the only status the old code ever wrote.
    CASE WHEN f.status ILIKE 'pending%' OR f.status IS NULL THEN 'open' ELSE 'closed' END,
    'operation',
    '../operation/operation_batch_detail.html?batch=' || COALESCE(f.batch_name, ''),
    f.batch_name,
    'system (migrated)',
    -- operation_follow_up_cases was created outside this repo, so its exact
    -- columns are not known here. Reading created_at through to_jsonb means
    -- a table without that column yields NULL instead of failing the whole
    -- migration on an unresolved reference.
    COALESCE((to_jsonb(f)->>'created_at')::timestamptz, now())
  FROM public.operation_follow_up_cases f
  -- Re-runnable: skip anything already brought across.
  WHERE NOT EXISTS (
    SELECT 1 FROM nelos_cases c
     WHERE c.source_module = 'operation'
       AND c.batch_name IS NOT DISTINCT FROM f.batch_name
       AND c.category    IS NOT DISTINCT FROM COALESCE(f.issue_type, 'Other')
       AND c.raised_by   = 'system (migrated)'
  );

  GET DIAGNOSTICS moved = ROW_COUNT;
  RAISE NOTICE 'Absorbed % follow-up case(s) into nelos_cases.', moved;
END $$;

-- ────────────────────────────────────────────────────────────────
-- PART 6: Check it landed
-- ────────────────────────────────────────────────────────────────
SELECT 'nelos_categories'    AS table_name, count(*) AS rows FROM nelos_categories
UNION ALL
SELECT 'nelos_cases',              count(*) FROM nelos_cases
UNION ALL
SELECT 'nelos_cases (pending)',    count(*) FROM nelos_cases WHERE status IN ('open','in_progress')
UNION ALL
SELECT 'nelos_case_comments',      count(*) FROM nelos_case_comments;

