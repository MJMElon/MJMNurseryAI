def iso(d):
    dd, mm, yyyy = d.split('/')
    return f'{yyyy}-{mm}-{dd}'


def values_sql():
    out = []
    for i, (d, batch, src, qty, dst) in enumerate(ROWS, start=1):
        out.append(f"  ({i}, DATE '{iso(d)}', {batch}, "
                   f"'{src}', {qty}, '{dst}')")
    return ',\n'.join(out)


