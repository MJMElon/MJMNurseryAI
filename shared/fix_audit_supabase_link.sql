-- ────────────────────────────────────────────────────────────────
-- 2. WHO MAY DO WHAT
--
--    Read / create / edit : any signed-in MJM account that is not a
--                           customer. This is the part that was broken —
--                           the old check also demanded an audit module
--                           permission that auditors were never given.
--    Delete               : admins only, as requested.
--
--    Note these are four separate policies, not one FOR ALL. Permissive
--    policies are OR-ed together, so a FOR ALL policy would hand DELETE
--    back to everyone and undo the admin restriction.
-- ────────────────────────────────────────────────────────────────

-- Is the caller a signed-in staff member (not a customer)?
CREATE OR REPLACE FUNCTION public._mjm_is_staff()
RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public
AS $fn$
  SELECT EXISTS (
    SELECT 1 FROM shared_profiles p
     WHERE p.id = auth.uid()
       AND COALESCE(p.user_type, 'system') <> 'customer'
  );
$fn$;

-- Is the caller an audit admin?
CREATE OR REPLACE FUNCTION public._mjm_is_audit_admin()
RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public
AS $fn$
  SELECT EXISTS (
    SELECT 1 FROM shared_profiles p
     WHERE p.id = auth.uid()
       AND ( lower(COALESCE(p.role, '')) IN ('admin', 'administrator')
          OR (p.permissions -> 'modules' ->> 'audit') = 'admin' )
  );
$fn$;

REVOKE ALL ON FUNCTION public._mjm_is_staff()          FROM PUBLIC;
REVOKE ALL ON FUNCTION public._mjm_is_audit_admin()    FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public._mjm_is_staff()       TO authenticated;
GRANT EXECUTE ON FUNCTION public._mjm_is_audit_admin() TO authenticated;

DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY[
    'audit_plot_audits',
    'audit_height_records',
    'audit_papan_audits',
    'audit_batches',
    'audit_maintenance_tasks',
    'audit_maintenance_audits'
  ] LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);

    -- Clear out every earlier attempt so re-running stays clean.
    EXECUTE format('DROP POLICY IF EXISTS "Authenticated full access" ON public.%I', t);
    EXECUTE format('DROP POLICY IF EXISTS "audit_module_read"  ON public.%I', t);
    EXECUTE format('DROP POLICY IF EXISTS "audit_module_write" ON public.%I', t);
    EXECUTE format('DROP POLICY IF EXISTS "audit_read"   ON public.%I', t);
    EXECUTE format('DROP POLICY IF EXISTS "audit_insert" ON public.%I', t);
    EXECUTE format('DROP POLICY IF EXISTS "audit_update" ON public.%I', t);
    EXECUTE format('DROP POLICY IF EXISTS "audit_delete" ON public.%I', t);

    EXECUTE format('CREATE POLICY "audit_read" ON public.%I
                    FOR SELECT TO authenticated
                    USING (public._mjm_is_staff())', t);
    EXECUTE format('CREATE POLICY "audit_insert" ON public.%I
                    FOR INSERT TO authenticated
                    WITH CHECK (public._mjm_is_staff())', t);
    EXECUTE format('CREATE POLICY "audit_update" ON public.%I
                    FOR UPDATE TO authenticated
                    USING (public._mjm_is_staff())
                    WITH CHECK (public._mjm_is_staff())', t);
    EXECUTE format('CREATE POLICY "audit_delete" ON public.%I
                    FOR DELETE TO authenticated
                    USING (public._mjm_is_audit_admin())', t);
  END LOOP;
END $$;


-- ────────────────────────────────────────────────────────────────
-- 3. PHOTOS
--    The app uploads to the audit-photos bucket and then renders the
--    /object/public/ URL, so the bucket has to be public to read and
--    writable by signed-in staff.
-- ────────────────────────────────────────────────────────────────
INSERT INTO storage.buckets (id, name, public)
VALUES ('audit-photos', 'audit-photos', true)
ON CONFLICT (id) DO UPDATE SET public = true;

DROP POLICY IF EXISTS "audit_photos_read"   ON storage.objects;
DROP POLICY IF EXISTS "audit_photos_insert" ON storage.objects;
DROP POLICY IF EXISTS "audit_photos_update" ON storage.objects;

CREATE POLICY "audit_photos_read" ON storage.objects
  FOR SELECT TO public
  USING (bucket_id = 'audit-photos');
CREATE POLICY "audit_photos_insert" ON storage.objects
  FOR INSERT TO authenticated
  WITH CHECK (bucket_id = 'audit-photos');
CREATE POLICY "audit_photos_update" ON storage.objects
  FOR UPDATE TO authenticated
  USING (bucket_id = 'audit-photos')
  WITH CHECK (bucket_id = 'audit-photos');

COMMIT;


